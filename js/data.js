// Loads the JSON content. Paths are resolved relative to this module so the site also works
// under a sub-path (e.g. GitHub Pages project sites: /<repo>/).
//
// Layout (one folder per destination, so destinations can be built in parallel):
//   data/countries.json                          countries, their regions/labels, destination ids
//   data/categories.json
//   data/destinations/<id>/destination.json      a destination (status: published | reference | draft)
//   data/destinations/<id>/locations.json        its locations (published destinations only)
//   data/destinations/<id>/photo-credits.json    generated by tools/photos.py
// A destination listed in countries.json whose folder does not exist yet is simply skipped.

const url = (rel) => new URL(`../${rel}`, import.meta.url);

async function getJSON(rel) {
  const res = await fetch(url(rel));
  if (!res.ok) throw new Error(`Không tải được ${rel} (${res.status})`);
  return res.json();
}

const optional = (rel, fallback) => getJSON(rel).catch(() => fallback);

async function loadDestination(id) {
  const dest = await optional(`data/destinations/${id}/destination.json`, null);
  if (!dest) return null;
  if (dest.status !== 'published') return { dest, locations: [], photos: [] };
  const [locations, photos] = await Promise.all([
    optional(`data/destinations/${id}/locations.json`, []),
    optional(`data/destinations/${id}/photo-credits.json`, []),
  ]);
  return { dest, locations, photos };
}

export async function loadData() {
  const [countries, categories] = await Promise.all([
    getJSON('data/countries.json'),
    getJSON('data/categories.json'),
  ]);
  const ids = [...new Set(countries.flatMap((c) => c.destinations.map((d) => `${c.id}/${d}`)))];
  const loaded = await Promise.all(ids.map(async (key) => {
    const [countryId, id] = key.split('/');
    const r = await loadDestination(id);
    if (r) r.dest.countryId = r.dest.countryId || countryId;
    return r;
  }));
  const parts = loaded.filter(Boolean);
  const destinations = parts.map((p) => p.dest).filter((d) => !['draft', 'planned'].includes(d.status));
  const locations = parts.flatMap((p) => p.locations).filter((l) => l.status === 'published');
  const photos = parts.flatMap((p) => p.photos);

  const countryById = (id) => countries.find((c) => c.id === id);
  return {
    countries: countries.filter((c) => c.status === 'published'),
    categories,
    destinations,
    locations,
    photos,
    countryById,
    destinationById: (id) => destinations.find((d) => d.id === id),
    destinationsOf: (country) => destinations.filter((d) => d.countryId === country.id),
    regionById: (countryId, id) => countryById(countryId)?.regions.find((r) => r.id === id),
    categoryById: (id) => categories.find((c) => c.id === id),
    // Locations in the order the destination lists them.
    locationsFor: (dest) => (dest.locationIds || [])
      .map((id) => locations.find((l) => l.id === id && l.destinationId === dest.id))
      .filter(Boolean),
    locationById: (id) => locations.find((l) => l.id === id),
    // Resolve an item's `images` ({photo, alt, illustrative}) to full photo records.
    imagesOf: (item) => (item.images || [])
      .map((img) => ({ ...photos.find((p) => p.id === img.photo), ...img }))
      .filter((p) => p.files),
  };
}

